fun String.parseToDoubleOrNull(): Double? {
    val cleaned = this.trim().replace(" ", "")
    if (cleaned.isEmpty()) return null
    
    // Check if both '.' and ',' are present, e.g. "12,345.67" or "12.345,67"
    if (cleaned.contains('.') && cleaned.contains(',')) {
        val lastDot = cleaned.lastIndexOf('.')
        val lastComma = cleaned.lastIndexOf(',')
        return if (lastDot > lastComma) {
            cleaned.replace(",", "").toDoubleOrNull()
        } else {
            cleaned.replace(".", "").replace(",", ".").toDoubleOrNull()
        }
    }
    
    // Check if it only has ',' and no '.', e.g. "12,5"
    if (cleaned.contains(',') && !cleaned.contains('.')) {
        val commaIndex = cleaned.lastIndexOf(',')
        val hasThreeDigitsAfter = (cleaned.length - 1 - commaIndex == 3)
        
        val noComma = cleaned.replace(",", "")
        val parsedNoComma = noComma.toDoubleOrNull()
        
        val commaToDot = cleaned.replace(',', '.')
        val parsedCommaToDot = commaToDot.toDoubleOrNull()
        
        if (hasThreeDigitsAfter) {
            if (parsedNoComma != null && parsedNoComma >= 1000.0) {
                return parsedNoComma
            }
        }
        return parsedCommaToDot ?: parsedNoComma
    }
    
    // Check if it only has '.' and no ',', e.g. "150.000"
    if (cleaned.contains('.') && !cleaned.contains(',')) {
        val dotIndex = cleaned.lastIndexOf('.')
        val hasThreeDigitsAfter = (cleaned.length - 1 - dotIndex == 3)
        
        if (hasThreeDigitsAfter) {
            val noDot = cleaned.replace(".", "")
            val parsedNoDot = noDot.toDoubleOrNull()
            if (parsedNoDot != null && parsedNoDot >= 1000.0) {
                return parsedNoDot
            }
        }
        return cleaned.toDoubleOrNull()
    }
    
    return cleaned.toDoubleOrNull()
}

fun String.parseToFloatOrNull(): Float? {
    return this.parseToDoubleOrNull()?.toFloat()
}

fun coerceInputString(input: String, maxLimit: Double, isInteger: Boolean = false): String {
    val doubleVal = input.parseToDoubleOrNull() ?: return input
    if (doubleVal > maxLimit) {
        return if (isInteger) maxLimit.toLong().toString() else {
            if (maxLimit % 1.0 == 0.0) maxLimit.toLong().toString() else maxLimit.toString()
        }
    }
    return input
}

